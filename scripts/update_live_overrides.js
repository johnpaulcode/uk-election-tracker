#!/usr/bin/env node
// Rebuilds data/live_overrides.js from the UK Parliament Members API.
//
//   node scripts/update_live_overrides.js          write the file
//   node scripts/update_live_overrides.js --dry    print the changes only
//
// A seat gets an override when its current MP sits for a different party than
// the one that won it in 2024, when the MP was elected after the general
// election (a by-election), or when the seat is vacant. Requires Node 18+.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'data', 'live_overrides.js');
const API = 'https://members-api.parliament.uk/api/Members/Search';
const GENERAL_ELECTION = '2024-07-04';
const PAGE = 20;

// Members API party abbreviations -> the codes used in data/results.js.
// Anything not listed is kept as the API gives it.
const PARTY_MAP = {
  'Lab/Co-op': 'Lab',
  Alliance: 'APNI',
  Reform: 'RUK',
  Ref: 'RUK',
  Speaker: 'Spk',
  GP: 'Green',
  Grn: 'Green'
};

function loadResults() {
  const src = fs.readFileSync(path.join(ROOT, 'data', 'results.js'), 'utf8');
  return new Function(src + '; return RESULTS;')();
}

const norm = s => s.normalize('NFD').replace(/[̀-ͯ]/g, '')
  .toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, ' ').trim();

async function fetchCurrentMPs() {
  const members = [];
  for (let skip = 0; ; skip += PAGE) {
    const res = await fetch(`${API}?House=1&IsCurrentMember=true&skip=${skip}&take=${PAGE}`);
    if (!res.ok) throw new Error(`Members API returned HTTP ${res.status}`);
    const body = await res.json();
    members.push(...body.items.map(i => i.value));
    if (skip + PAGE >= body.totalResults || body.items.length === 0) break;
  }
  return members;
}

async function main() {
  const dry = process.argv.includes('--dry');
  const RESULTS = loadResults();
  const codeByName = new Map(Object.entries(RESULTS).map(([code, r]) => [norm(r.name), code]));

  const members = await fetchCurrentMPs();
  const mpByCode = new Map();
  const unmatched = [];
  for (const m of members) {
    const seat = m.latestHouseMembership.membershipFrom;
    const code = codeByName.get(norm(seat));
    if (code) mpByCode.set(code, m); else unmatched.push(seat);
  }
  if (unmatched.length) {
    throw new Error('Could not match these constituencies to results.js: ' + unmatched.join(', '));
  }

  const overrides = {};
  for (const code of Object.keys(RESULTS).sort((a, b) => RESULTS[a].name.localeCompare(RESULTS[b].name))) {
    const r = RESULTS[code];
    const m = mpByCode.get(code);
    if (!m) {
      overrides[code] = { name: r.name, change: 'vacant', new_winner: 'Vacant', old_winner: r.winner, new_party: 'Vacant', old_party: r.party };
      continue;
    }
    const abbr = m.latestParty.abbreviation || m.latestParty.name;
    const party = PARTY_MAP[abbr] || abbr;
    const newMember = m.latestHouseMembership.membershipStartDate.slice(0, 10) > GENERAL_ELECTION;
    if (!newMember && party === r.party) continue;
    overrides[code] = {
      name: r.name,
      change: newMember ? 'by-election' : 'party',
      since: newMember ? m.latestHouseMembership.membershipStartDate.slice(0, 10) : undefined,
      new_winner: m.nameDisplayAs.replace(/^(Mr|Mrs|Ms|Miss) /, ''),
      old_winner: r.winner,
      new_party: party,
      old_party: r.party
    };
  }

  const list = Object.values(overrides);
  console.log(`${members.length} current MPs; ${list.length} seats differ from the 2024 result:`);
  for (const o of list) {
    console.log(`  ${o.name}: ${o.old_winner} (${o.old_party}) -> ${o.new_winner} (${o.new_party}) [${o.change}]`);
  }

  if (dry) return;
  const today = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(OUT,
    '// Generated by scripts/update_live_overrides.js from the UK Parliament Members API.\n' +
    '// Do not edit by hand; re-run the script to refresh.\n' +
    `const LIVE_OVERRIDES_UPDATED = ${JSON.stringify(today)};\n\n` +
    `const LIVE_OVERRIDES = ${JSON.stringify(overrides, null, 2)};\n`);
  console.log(`Wrote ${path.relative(ROOT, OUT)}`);
}

main().catch(err => { console.error(err.message); process.exit(1); });
